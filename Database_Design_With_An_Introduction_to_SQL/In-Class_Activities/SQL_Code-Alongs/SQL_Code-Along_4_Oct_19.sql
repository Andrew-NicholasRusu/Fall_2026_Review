-- Result 1
SELECT V_CODE, V_NAME, SUM(P_PRICE * Q_QOH)
FROM VENDOR JOIN PRODUCT USING(V_CODE)
WHERE P_DISCOUNT > 0
GROUP BY V_CODE, V_NAME
HAVING SUM(P_PRICE * Q_QOH) > 500
ORDER BY SUM(P_PRICE * P_QOH) DESC;

-- Result 2
SELECT V_CODE, V_NAME, SUM(P_PRICE * Q_QOH) AS TOTAL
FROM VENDOR JOIN PRODUCT USING(V_CODE)
WHERE P_DISCOUNT > 0
GROUP BY V_CODE, V_NAME
HAVING TOTAL > 500
ORDER BY TOTAL DESC;

-- Result 3
SELECT V_CODE, V_NAME
FROM VENDOR JOIN PRODUCT USING(V_CODE)
WHERE DISCOUNT > 0;

-- Result 4
SELECT P_CODE, P_PRICE
FROM PRODUCT
WHERE P_PRICE > (SELECT AVG(P_PRICE) FROM PRODUCT);

-- Result 5
SELECT V_CODE, V_NAME
FROM PRODUCT RIGHT JOIN VENDOR USING (V_CODE)
WHERE P_CODE IS NULL;

-- Result 6
SELECT V_CODE, V_NAME
FROM VENDOR
WHERE V_CODE NOT IN(SELECT V_CODE FROM PRODUCT
WHERE V_CODE IS NOT NULL);

