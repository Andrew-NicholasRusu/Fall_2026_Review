DROP PROCEDURE IF EXISTS MUL_PROC;
DELIMITER $$
CREATE PROCEDURE MUL_PROC()
BEGIN 
	DECLARE NUM1 NUMERIC(1) DEFAULT 5;
    DECLARE NUM2 NUMERIC(1);
    DECLARE TOTAL INT;
    DECLARE MESSAGE VARCHAR(50) DEFAULT 'The total is: ';
    
    SET NUM2=6;
    SET TOTAL = NUM1 * NUM2;
    SELECT CONCAT(MESSAGE, TOTAL) AS RESULT;
END;
$$
DELIMITER ;
CALL MUL_PROC();

DROP PROCEDURE IF EXISTS COND_PROC;
DELIMITER $$
CREATE PROCEDURE COND_PROC()
BEGIN 
	DECLARE NUM1 INT DEFAULT 5;
    DECLARE NUM2 INT DEFAULT 60;
    DECLARE TOTAL INT;
    DECLARE MESSAGE VARCHAR(50);
    
    SET TOTAL = NUM1 * NUM2;
    IF TOTAL < 50 THEN
		SET MESSAGE = "The total is small: ";
	ELSE
		SET MESSAGE = "The total is large: ";
    END IF;
	SELECT CONCAT (MESSAGE, TOTAL) AS RESULT;
END;
$$
DELIMITER ;
CALL CON_PROC;

DROP PROCEDURE IF EXISTS TOTAL_PROC;
DELIMITER $$
CREATE PROCEDURE TOTAL_PROC()
BEGIN 
	DECLARE NUM1 INT DEFAULT 50;
    DECLARE NUM2 INT DEFAULT 100;
    DECLARE TOTAL INT;
    DECLARE MESSAGE VARCHAR(50);
    
    SET TOTAL = NUM1 * NUM2;
    IF TOTAL < 100 THEN
		SET MESSAGE = "The total is small: ";
	ELSEIF TOTAL > 100 AND TOTAL <= 500 THEN
		SET MESSAGE = "The total is medium: ";
	ELSEIF TOTAL BETWEEN 500 AND 1000 THEN 
		SET MESSAGE="The total is large:";
	ELSE 
		SET MESSAGE = "The total is huge: ";
    END IF;
	SELECT CONCAT (MESSAGE, TOTAL) AS RESULT;
END;
$$
DELIMITER ;
CALL TOTAL_PROC;

DROP PROCEDURE IF EXISTS LOOP_PROC;
DELIMITER $$ 
CREATE PROCEDURE LOOP_PROC()
BEGIN
	DECLARE MYNUM INT DEFAULT 1;
    DECLARE RESULT VARCHAR(100) DEFAULT MYNUM;
    COUNTER:LOOP
    SET MYNUM = MYNUM + 1;
    IF MYNUM > 20 THEN
		LEAVE COUNTER;
	END IF;
    SET RESULT = CONCAT(RESULT, ',', MYNUM);
    END LOOP;
    SELECT RESULT;
END;
$$
DELIMITER ;
CALL LOOP_PROC;

DROP PROCEDURE IF EXISTS WHILE_PROC;
DELIMITER $$ 
CREATE PROCEDURE WHILE_PROC()
BEGIN
	DECLARE MYNUM INT DEFAULT 1;
    DECLARE RESULT VARCHAR(100) DEFAULT MYNUM;
	WHILE MYNUM < 20 DO
		SET MYNUM = MYNUM + 1;
        SET RESULT = CONCAT(RESULT,',', MYNUM);
	END WHILE;
    SELECT RESULT;
END;
$$
DELIMITER ;
CALL WHILE_PROC;










