# List all the customers (Customer Code, Last Name, First Name) that ordered Hammers, Saw, or Saw blades.
SELECT DISTINCT CUS_CODE, CUS_LNAME, CUS_FNAME
FROM CUSTOMER JOIN INVOICE USING(CUS_CODE)
JOIN LINE USING(INV_NUMBER) JOIN PRODUCT USING(P_CODE)
WHERE P_CODE=(SELECT P_CODE FROM PRODUCT
WHERE P_DESCRIPT="CLAW HAMMER" OR "SAW" OR "SAW BLADE");

-- Another method
SELECT DISTINCT CUS_CODE, CUS_LNAME, CUS_FNAME
FROM CUSTOMER JOIN INVOICE USING(CUS_CODE)
JOIN LINE USING(INV_NUMBER) JOIN PRODUCT USING(P_CODE)
WHERE P_CODE IN (SELECT P_CODE FROM PRODUCT
WHERE P_DESCRIPT LIKE "%hammer%" OR P_DESCRIPT LIKE "%SAW%"); -- Selects anything that contains 'hammer' or 'saw'

-- Result 2

# List all the products with total quantity sold greater than the average quantity sold.
SELECT P_CODE, SUM(LINE_UNITS)
FROM LINE
GROUP BY P_CODE
HAVING SUM(LINE_UNITS)>(SELECT AVG(LINE_UNITS) FROM LINE);

-- Result 3

# List P_CODE, P_PRICE, AVERAGE PRODUCT PRICE, difference between each product price & AVERAGE PRODUCT PRICE
SELECT P_CODE, P_PRICE, (SELECT AVG (P_PRICE) FROM PRODUCT) AS AVGPRICE, -- AVGPRICE = new name for AVERAGE PRODUCT PRICE
P_PRICE - (SELECT AVG(P_PRICE) FROM PRODUCT) AS DIFF -- DIFF = new name for difference
FROM PRODUCT;

