ALTER TABLE PRODUCT 
ADD P_REORDER INTEGER; 

DROP TRIGGER IF EXISTS TRG_REORDER_TEST;
DELIMITER $$
CREATE TRIGGER TRG_REORDER_TEST
AFTER UPDATE ON PRODUCT
FOR EACH ROW 
BEGIN 
	UPDATE PRODUCT
    SET P_REORDER = 1
    WHERE P_QOH <= P_MIN;
END;
$$
DELIMITER ;
START TRANSACTION;
UPDATE PRODUCT SET P_QOH = 2 WHERE P_CODE ='11QER/31';
SELECT *
FROM PRODUCT;
ROLLBACK;



