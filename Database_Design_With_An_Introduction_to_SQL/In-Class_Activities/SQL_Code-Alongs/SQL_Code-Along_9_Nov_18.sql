DROP PROCEDURE IF EXISTS WHILE_PROC;
DELIMITER $$ 
CREATE PROCEDURE WHILE_PROC()
BEGIN
	DECLARE NUM INT DEFAULT 1;
    DECLARE RESULT VARCHAR(100) DEFAULT NUM;
    WHILE NUM < 20 DO
		SET NUM = NUM + 1;
        SET RESULT= CONCAT(RESULT, ', ', NUM);
	END WHILE;
    SELECT RESULT;
END;
$$
DELIMITER ;
CALL WHILE_PROC;

