DROP PROCEDURE IF EXISTS TABLE_PROC;
DELIMITER $$
CREATE PROCEDURE TABLE_PROC()
BEGIN
	DECLARE NUM INT DEFAULT 1;
    CREATE TEMPORARY TABLE MYTAB(RESULT VARCHAR(100));
    WHILE NUM <= 5 DO
		INSERT INTO MYTAB VALUES(CONCAT('The current num is: ', NUM));
        SET NUM = NUM + 1;
	END WHILE;
    SELECT * FROM MYTAB;
    DROP TABLE MYTAB;
END;
$$ 
DELIMITER ;
CALL TABLE_PROC();

DROP PROCEDURE IF EXISTS CURSOR_PROC;
DELIMITER $$
CREATE PROCEDURE CURSOR_PROC()
BEGIN 	
	DECLARE W_P_CODE VARCHAR(15);
    DECLARE W_P_DESCRIPT VARCHAR(50);
    DECLARE NOTFOUND INT DEFAULT 0;
    DECLARE PROD_CURSOR CURSOR FOR SELECT P_CODE, P_DESCRIPT
									FROM PRODUCT
                                    WHERE P_QOH > (SELECT AVG(P_QOH) 
													FROM PRODUCT);
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET NOTFOUND = 1;
    DROP TEMPORARY TABLE IF EXISTS MYTAB;
    CREATE TEMPORARY TABLE MYTAB(RESULT VARCHAR(100));
    OPEN PROD_CURSOR;
    GET_PRODUCTS: LOOP
		FETCH PROD_CURSOR INTO W_P_CODE, W_P_DESCRIPT;
        IF NOTFOUND = 1 THEN 
			LEAVE GET_PRODUCTS;
		END IF;
        INSERT INTO MYTAB VALUES(CONCAT(W_P_CODE, ' -> ', W_P_DESCRIPT));
	END LOOP;
    CLOSE PROD_CURSOR;
    SELECT RESULT AS 'PRODUCTS WITH P_QOH > AVG(P_QOH))' FROM MYTAB;
    DROP TABLE MYTAB;
END;
$$ 
DELIMITER ;
CALL CURSOR_PROC();





