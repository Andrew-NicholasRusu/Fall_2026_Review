-- ASSIGN 5 PERCENT DISCOUNT TO ALL THE PRODUCTS 
-- WHEN QUANTITY ON HAND IS MORE THAN OR EQUAL TO TWICE THE MINIMUM QUANTITY

DROP PROCEDURE IF EXISTS PRC_PROD_DISCOUNT;
DELIMITER $$
CREATE PROCEDURE PRC_PROD_DISCOUNT()
BEGIN
	UPDATE PRODUCT
	SET P_DISCOUNT = P_DISCOUNT + 0.05
    WHERE P_QOH >= P_MIN * 2;
END;
START TRANSACTION;
CALL PRC_PROC_DISCOUNT;
SELECT P_CODE, P_DESCRIPT, P_QOH, P_MIN, P_DISCOUNT FROM PRODUCT;
ROLLBACK;
$$ 
