-- Another Method
DROP PROCEDURE IF EXISTS DIS_PROC;
DELIMITER $$ 
CREATE PROCEDURE DIS_PROC(IN WPI DECIMAL (2,2))
BEGIN
	IF WPI < 0 OR WPI > 1 THEN 
		SELECT 'ERROR: VALUE MUST BE MORE THAN 0 AND LESS THAN 1';
	ELSE 
		UPDATE PRODUCT
        SET P_DISCOUNT = P_DISCOUNT + WPI
        WHERE P_QOH >= P_MIN * 2;
	END IF;
END;
$$
DELIMITER ;
START TRANSACTION;
CALL DIS_PROC(0.33);

SELECT P_CODE, P_DESCRIPT, P_QOH, P_MIN, P_DISCOUNT FROM PRODUCT;
ROLLBACK;






