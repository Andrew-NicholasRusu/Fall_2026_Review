-- Creates a new schema name "MYPRACTICE"
CREATE SCHEMA MYPRACTICE;
USE MYPRACTICE;

CREATE TABLE VENDOR(
V_CODE INTEGER NOT NULL UNIQUE,
V_NAME VARCHAR(35) NOT NULL,
V_CONTACT VARCHAR(25) NOT NULL,
V_AREACODE CHAR(3) NOT NULL,
V_PHONE CHAR(8) NOT NULL,
V_STATE CHAR(2),
V_ORDER CHAR(1) NOT NULL,
PRIMARY KEY (V_CODE));

CREATE TABLE PRODUCT(
P_CODE VARCHAR(10) NOT NULL UNIQUE,
P_DESCRIPT VARCHAR(35) NOT NULL, 
P_INDATE DATE NOT NULL,
P_QOH SMALLINT NOT NULL, 
P_MIN SMALLINT NOT NULL,
P_PRICE NUMERIC (8, 2) NOT NULL,
P_DISCOUNT NUMERIC(5, 2) NOT NULL,
V_CODE INTEGER,
PRIMARY KEY(P_CODE),
FOREIGN KEY (V_CODE) REFERENCES VENDOR(V_CODE)
);

CREATE TABLE CUSTOMER(
CUS_CODE INTEGER PRIMARY KEY,
CUS_LNAME VARCHAR(15) NOT NULL,
CUS_FNAME VARCHAR(15) NOT NULL,
CUS_INITIAL CHAR(1),
CUS_AREACODE CHAR(3) DEFAULT '615' NOT NULL
				CHECK(CUS_AREACODE IN ('613', '713', '931')),
CUS_PHONE CHAR(8) NOT NULL,
CUS_BALANCE NUMERIC(9,2) DEFAULT 0.00);

-- Create Table: INVOICE
CREATE TABLE INVOICE(
INV_NUMBER INTEGER PRIMARY KEY,
CUST_CODE INTEGER NOT NULL REFERENCES CUSTOMER(CUS_CODE),
INV_DATE DATE CHECK(INV_DATE < '2022-01-01'));

CREATE TABLE LINE(
INV_NUMBER INTEGER NOT NULL,
LINE_NUMBER INTEGER NOT NULL,
P_CODE VARCHAR(10) NOT NULL, -- VARCHAR: Character with valuable lengths
LINE_UNITS SMALLINT DEFAULT 0 NOT NULL,
LINE_PRICE NUMERIC(9,2) DEFAULT 0.00 NOT NULL, -- Decimal value (2), 9 digits
PRIMARY KEY (INV_NUMBER, LINE_NUMBER),
FOREIGN KEY (INV_NUMBER) REFERENCES INVOICE(INV_NUMBER),
FOREIGN KEY (P_CODE) REFERENCES PRODUCT(P_CODE),
CONSTRAINT LINE_UNI UNIQUE(INV_NUMBER, P_CODE)
);

